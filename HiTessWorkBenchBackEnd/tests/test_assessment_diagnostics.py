# redact_paths — 서버 절대경로 비노출
# ══════════════════════════════════════════════════════════════
class TestRedactPaths:
    def test_work_dir_replaced_with_placeholder(self):
        work_dir = r"C:\KHM\HiTessWorkbench\userConnection\20260730_1_TrussAssessment"
        text = rf"BDF 파일: {work_dir}\200K.bdf"
        out = redact_paths(text, work_dir)
        assert work_dir not in out
        assert "200K.bdf" in out

    def test_case_insensitive_on_windows(self):
        work_dir = r"C:\KHM\userConnection\Job1"
        out = redact_paths(r"열기 실패: c:\khm\userconnection\job1\a.f06", work_dir)
        assert "c:\\khm" not in out.lower()

    def test_none_work_dir_is_safe(self):
        assert redact_paths("plain text", None) == "plain text"


# ══════════════════════════════════════════════════════════════
# build_failure_report — Execution Console 에 찍히는 최종 텍스트
# ══════════════════════════════════════════════════════════════
class TestBuildFailureReport:
    def test_report_contains_cause_and_remedy(self):
        d = diagnose_engine_failure(TestDiagnoseEngineFailure.REAL_OUTPUT)
        report = build_failure_report(
            diagnosis=d,
            engine_output=TestDiagnoseEngineFailure.REAL_OUTPUT,
            work_dir=None,
        )
        assert "[원인]" in report
        assert "[조치]" in report
        assert "SPCFORCES(PRINT,PUNCH)" in report

    def test_report_includes_engine_output_tail(self):
        report = build_failure_report(
            diagnosis=None,
            engine_output="line-A\nline-B\nUnhandled exception. Boom\n",
            work_dir=None,
        )
        assert "Unhandled exception. Boom" in report

    def test_report_without_diagnosis_still_shows_raw_output(self):
        report = build_failure_report(diagnosis=None, engine_output="무언가 이상함", work_dir=None)
        assert "무언가 이상함" in report

    def test_report_redacts_work_dir(self):
        work_dir = r"C:\KHM\userConnection\Job9"
        report = build_failure_report(
            diagnosis=None,
            engine_output=rf"파일 없음: {work_dir}\x.f06",
            work_dir=work_dir,
        )
        assert work_dir not in report

    def test_engine_output_is_tail_limited(self):
        huge = "\n".join(f"line{i}" for i in range(5000))
        report = build_failure_report(diagnosis=None, engine_output=huge, work_dir=None)
        assert len(report) < 20000
        assert "line4999" in report  # 마지막(가장 중요한) 줄은 반드시 남는다
