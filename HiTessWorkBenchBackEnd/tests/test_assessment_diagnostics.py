# read_case_control_head — BEGIN BULK 까지만 읽기
# ══════════════════════════════════════════════════════════════
class TestReadCaseControlHead:
    def test_stops_at_begin_bulk(self, tmp_path):
        bdf = tmp_path / "m.bdf"
        bdf.write_text(FAILING_BDF + "GRID 2\n" * 100_000, encoding="utf-8")
        head = read_case_control_head(str(bdf))
        assert "SPCFORCES(PUNCH)" in head
        assert head.count("GRID 2") <= 1  # BEGIN BULK 이후는 읽지 않는다

    def test_missing_file_returns_none(self, tmp_path):
        assert read_case_control_head(str(tmp_path / "nope.bdf")) is None

    def test_result_is_parseable_by_preflight(self, tmp_path):
        bdf = tmp_path / "m.bdf"
        bdf.write_text(FAILING_BDF, encoding="utf-8")
        problems = preflight_case_control(read_case_control_head(str(bdf)))
        assert [p.command for p in problems if p.blocking] == ["SPCFORCES"]


