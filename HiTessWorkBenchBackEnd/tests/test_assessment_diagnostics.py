# diagnose_engine_failure — 엔진 출력에서 실패 서명 인식
# ══════════════════════════════════════════════════════════════
class TestDiagnoseEngineFailure:
    REAL_OUTPUT = """\
[2026-07-30 14:35:47.757] [INFO ] BDF 파싱 완료 - GRID: 11472, CBAR: 15298, SUBCASE: 7
No displacement data found.
No SPC Force data found.
[2026-07-30 14:35:48.224] [WARN ] SPCForce 파싱 결과가 없습니다.
[2026-07-30 14:35:48.253] [INFO ] 부재 검토 완료 - 총 107086개 평가, Fail: 0개
[2026-07-30 14:35:48.253] [INFO ] 하중분산판 검토 수행 중...
Unhandled exception. System.Collections.Generic.KeyNotFoundException: The given key 'SPCForce' was not present in the dictionary.
   at TrussAssessment.Control.LoadDistributionChecker.Run()
"""

    def test_recognizes_missing_spcforce(self):
        d = diagnose_engine_failure(self.REAL_OUTPUT)
        assert d is not None
        assert "SPCFORCES(PRINT,PUNCH)" in d.remedy
        assert "SPC 반력" in d.cause

    def test_recognizes_missing_elforce(self):
        d = diagnose_engine_failure(
            "No EL Force data found.\n"
            "Unhandled exception. System.Collections.Generic.KeyNotFoundException: "
            "The given key 'ELForce' was not present in the dictionary.\n"
        )
        assert "ELFORCE(PRINT,PUNCH)" in d.remedy

    def test_recognizes_f06_fatal(self):
        d = diagnose_engine_failure(
            "[FATAL] F06 FATAL 발견 (Line 812): *** USER FATAL MESSAGE 5423\n"
        )
        assert "FATAL" in d.cause
        assert d.stage == "Nastran 해석"

    def test_recognizes_missing_f06(self):
        d = diagnose_engine_failure("[ERROR] .f06 파일을 찾을 수 없습니다. Nastran 실행이 실패했을 수 있습니다.\n")
        assert "Nastran" in d.cause

    def test_recognizes_zero_element_evaluation(self):
        """104leg.bdf 사례 — Property ID 가 허용응력 테이블(1~18)과 어긋난 경우."""
        d = diagnose_engine_failure("[INFO ] 부재 검토 완료 - 총 0개 평가, Fail: 0개\n")
        assert "Property ID" in d.cause

    def test_recognizes_timeout(self):
        d = diagnose_engine_failure("해석 엔진이 제한 시간(600초)을 초과했습니다. 관리자에게 문의하세요.")
        assert "제한 시간" in d.cause

    def test_unknown_output_returns_none(self):
        assert diagnose_engine_failure("[INFO ] 모든 작업이 완료되었습니다.\n") is None

    def test_empty_output_returns_none(self):
        assert diagnose_engine_failure("") is None


